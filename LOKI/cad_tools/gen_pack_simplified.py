"""Generate a SIMPLIFIED CAD pack-component set: the parts beyond both straw ends of every pack (the 'slabs' of a
gen_pack.py configuration, e.g. cfg_pack_ends.json: the end blocks SI-7615-134/-135 and the end plates SI-7615-073) as
two homogenised boxes per end, which fill the pack volume (G4Para) beyond the straw ends between the first and the last
slab: the upper half (y > 0) and the lower half (y < 0) of the parallelogram section, each as wide as the shear of the
Para allows. The whole CAD volume of the slabs (section area x slab length) is kept: each box has half of it, as its
density factor (fill). (The real pack is wider and longer than the Geant4 pack volume: the material is compressed into
it.)

usage: python gen_pack_simplified.py CONFIG.json OUTPUT NAME"""
import sys
import json
import os
import numpy as np
from gen_pack import M, T2, DX, DY, ALPHA, GAP


def area(poly):
    x, y = np.array(poly).T
    return 0.5 * abs(np.dot(x, np.roll(y, 1)) - np.dot(y, np.roll(x, 1)))


def main(cfg, output, name):
    C = json.load(open(cfg))
    volume = 0.0; a_min = 1e9; b_max = -1e9; parts = []
    for part in C['parts']:
        parts.append(part['label'])
        for slab in part.get('slabs', []):
            S = json.load(open(os.path.expandvars(slab['section'])))
            A = 0.0
            for wires in S.values():                 # the outer wire minus the holes
                ar = sorted((area((M @ np.array(w).T).T + T2) for w in wires if len(w) > 2), reverse=True)
                A += ar[0] - sum(ar[1:]) if ar else 0.0
            volume += A * (slab['b'] - slab['a'])
            a_min = min(a_min, slab['a']); b_max = max(b_max, slab['b'])
    t = np.tan(ALPHA); m = GAP / np.cos(ALPHA)
    y0, y1 = GAP, DY - GAP                            # upper half: |x - y tan(alpha)| <= DX for y in [y0, y1]
    upper = (-DX + y1 * t + m, DX + y0 * t - m, y0, y1)
    lower = (-DX - y0 * t + m, DX - y1 * t - m, -y1, -y0)
    lines = []
    for label, (x0, x1, ya, yb) in (('upper', upper), ('lower', lower)):
        box = (x1 - x0) * (yb - ya) * (b_max - a_min)
        fill = 0.5 * volume / box
        if fill > 1:
            sys.exit(f'the material does not fit: fill {fill:.2f}')
        lines.append(f"ends.{label} Al {x0:.3f} {x1:.3f} {ya:.3f} {yb:.3f} ends {a_min:.3f} {b_max:.3f} {fill:.4f}")
    with open(output, 'w') as f:
        f.write(f"# LOKI CAD pack component set '{name}' (simplified): the parts beyond both straw ends of every pack "
                f"({', '.join(parts)}: {volume / 1e3:.0f} cm3 per end) as two homogenised aluminium boxes per end (upper / lower half "
                f"of the pack section), filling the pack volume between {a_min:.1f} and {b_max:.1f} mm beyond the straw end\n")
        f.write(f"# generated by gen_pack_simplified.py from {os.path.basename(cfg)}; boxes in the frame of the detector pack "
                "(EmptyPackBox: x = depth, y = across the tubes)\n")
        f.write("# one box per line: name material x0 x1 y0 y1 [mm] zkind a b fill; zkind ends: z in [L/2+a, L/2+b] and its mirror "
                "image (L: straw length); fill: the density factor\n")
        f.write('\n'.join(lines) + '\n')
    print(f"{name}: {len(lines)} boxes per end, {volume / 1e3:.0f} cm3 per end, written to {output}")
    print('\n'.join(lines))


if __name__ == '__main__':
    main(*sys.argv[1:4])
